#!/usr/bin/env python3
"""Generate src/bend.inc: exact pitch bend curves as period-offset factors.

A GB period register x relates to frequency by f = 131072 / (2048 - x), so with
P = 2048 - x the pitch ratio 2^(s/12) means P' = P / 2^(s/12):
    bend up   by s semitones:  x' = x + P * (1 - 2^(-s/12))
    bend down by s semitones:  x' = x - P * (2^(s/12) - 1)
The ROM looks the factor up by m = |bend| * range / 4 (0..192), where |bend| is
the MIDI MSB distance from the centre (1..64) and range is in semitones (1..12),
so the bend in semitones is s = m / 16. Factors are scaled by 128 (max 128).
"""
STEPS = 193

print("; GENERATED by tools/gen_bend.py -- do not edit by hand")
print("; index m = |bend| * range / 4; factor = round(128 * ratio); semitones = m / 16")
for name, f in (("BendUp", lambda s: 1 - 2 ** (-s / 12)), ("BendDown", lambda s: 2 ** (s / 12) - 1)):
    vals = [round(128 * f(m / 16)) for m in range(STEPS)]
    assert max(vals) <= 128
    print(f"{name}:")
    for i in range(0, STEPS, 16):
        print("    db " + ",".join(str(x) for x in vals[i:i + 16]))
