#!/usr/bin/env python3
"""Generate src/waves.inc: preset CH3 waveforms (32 x 4-bit -> 16 bytes each)."""
import math

N = 32


def square():
    return [15 if i < 16 else 0 for i in range(N)]


def saw():
    return [round(i * 15 / (N - 1)) for i in range(N)]


def triangle():
    return [i if i < 16 else 31 - i for i in range(N)]


def sine():
    return [round(7.5 + 7.5 * math.sin(2 * math.pi * i / N)) for i in range(N)]


WAVES = [("SQUARE", square()), ("SAW", saw()), ("TRIANGLE", triangle()), ("SINE", sine())]

print("; GENERATED by tools/gen_waves.py -- do not edit by hand")
print(f"DEF WAVE_COUNT EQU {len(WAVES)}")
print("Waves:")
for name, s in WAVES:
    b = [(s[i] << 4) | s[i + 1] for i in range(0, N, 2)]
    print("    db " + ",".join(f"${x:02X}" for x in b) + f" ; {name}")
