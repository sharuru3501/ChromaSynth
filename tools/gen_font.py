# --- piano roll tiles: 8 rows of 8 pixels, each pixel a colour index 0-3
def rows(*r):
    return list(r)


EMP_W = ["00000000"] * 7 + ["11111111"]               # white-key row: faint line below
EMP_B = ["11111111"] * 8                               # black-key row: shaded band
BEAT = lambda t: ["2" + r[1:] for r in t]              # beat line at the left edge
NOTE_BODY = ["00000000"] + ["33333333"] * 6 + ["00000000"]
NOTE_HEAD = ["00000000"] + ["03333333"] * 6 + ["00000000"]
CUR_EMP = ["33333333"] + ["30000003"] * 6 + ["33333333"]
CUR_NOTE = ["33333333"] + ["32222223"] * 6 + ["33333333"]
PLAYHEAD = ["00011000"] * 8                            # sprite: colour 1 = red

ROLL_TILES = {  # tile index -> pixels
    64: EMP_W,
    65: EMP_B,
    66: BEAT(EMP_W),
    67: BEAT(EMP_B),
    68: NOTE_HEAD,
    69: NOTE_BODY,
    70: CUR_EMP,
    71: CUR_NOTE,
    72: PLAYHEAD,
}


def pixels_to_tile(px):
    out = []
    for row in px:
        lo = hi = 0
        for x, c in enumerate(row):
            v = int(c)
            lo |= (v & 1) << (7 - x)
            hi |= ((v >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out


tiles = []
for code in range(32, 96):
    rws = GLYPHS.get(chr(code), [0] * 7) + [0]
    data = []
    for r in rws:
        b = (r << 3) & 0xFF
        data += [b, b]
    tiles.append((data, repr(chr(code))))
while len(tiles) < 64:
    tiles.append(([0] * 16, "-"))
for idx in range(64, 128):
    if idx in ROLL_TILES:
        tiles.append((pixels_to_tile(ROLL_TILES[idx]), f"roll tile {idx}"))
    else:
        tiles.append(([0] * 16, "-"))
for data, name in tiles[:64]:
    tiles.append(([b ^ 0xFF for b in data], "inv " + name))

print("; GENERATED by tools/gen_font.py -- do not edit by hand")
print("; 192 tiles: 0-63 text, 64-72 piano roll, 128-191 inverted text")
print("Font:")
for data, name in tiles:
    print("    db " + ",".join(f"${b:02X}" for b in data) + f" ; {name}")
print("FontEnd:")
print(f"DEF FONT_TILES EQU {len(tiles)}")
