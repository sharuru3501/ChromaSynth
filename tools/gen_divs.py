#!/usr/bin/env python3
"""Generate src/divs.inc: grid division tables for the piano roll.

A grid division is how many ticks one roll column covers (12 ticks = 1 beat).
For each division: ticks per cell, cells per full pattern, a label and the
playhead pixel table (x = floor(dt * 8 / ticks), dt = ticks since the page start).
"""
TICKS_PER_PATTERN = 192
PAGE_COLS = 16
DIVS = [  # (label, ticks per cell)
    ("1/4", 12),
    ("1/4T", 8),
    ("1/8", 6),
    ("1/8T", 4),
    ("1/16", 3),
    ("1/16T", 2),
    ("1/48", 1),
]
assert all(TICKS_PER_PATTERN % t == 0 for _, t in DIVS)

print("; GENERATED by tools/gen_divs.py -- do not edit by hand")
print(f"DEF NUM_DIVS_GEN EQU {len(DIVS)}")
print("DivTicks:  db " + ", ".join(str(t) for _, t in DIVS))
print("DivCells:  db " + ", ".join(str(TICKS_PER_PATTERN // t) for _, t in DIVS) + "  ; cells in the whole pattern")
print("DivLabels:  ; 6 bytes each: 5 characters + terminator")
for label, _ in DIVS:
    print(f'    db "{label:<5}", 0')
print("PlayXPtrs: dw " + ", ".join(f"PlayX{i}" for i in range(len(DIVS))))
for i, (label, t) in enumerate(DIVS):
    xs = [dt * 8 // t for dt in range(PAGE_COLS * t)]
    print(f"PlayX{i}:  ; {label}: {len(xs)} entries")
    for j in range(0, len(xs), 16):
        print("    db " + ",".join(str(x) for x in xs[j:j + 16]))
