#!/usr/bin/env python3
"""Generate src/divs.inc: grid division tables for the piano roll.

A grid division is how many ticks one roll column covers (12 ticks = 1 beat).
Every page has 16 columns, so the screen is never left blank. A page starts on a multiple of its
span, except the last page of a segment when the segment is not a whole number of pages: it is
shifted back so that it ends on the segment end (the pages overlap). Bars are tracked by tick, so
they stay where they are when the division changes.
For each division: ticks per cell, columns per page (<= 16), ticks per page,
cells per full pattern, a label and the playhead pixel table
(x = floor(dt * 8 / ticks), dt = ticks since the page start).
"""
TICKS_PER_PATTERN = 192
PAGE_COLS = 16
DIVS = [  # (label, ticks per cell, columns per page)
    ("1/4", 12, 16),    # 4 bars per page
    ("1/4T", 8, 16),    # 128 ticks (24 cells in a segment: the 2nd page shows cells 8-23)
    ("1/8", 6, 16),     # 2 bars
    ("1/8T", 4, 16),    # 64 ticks
    ("1/16", 3, 16),    # 1 bar
    ("1/16T", 2, 16),   # 32 ticks
    ("1/48", 1, 16),    # 16 ticks
]
for _, t, c in DIVS:
    assert c <= PAGE_COLS
    assert c == PAGE_COLS and TICKS_PER_PATTERN % t == 0 and t * c <= TICKS_PER_PATTERN

print("; GENERATED by tools/gen_divs.py -- do not edit by hand")
print(f"DEF NUM_DIVS_GEN EQU {len(DIVS)}")
print("DivTicks:  db " + ", ".join(str(t) for _, t, _ in DIVS))
print("DivCols:   db " + ", ".join(str(c) for _, _, c in DIVS) + "  ; grid columns per page")
print("DivSpan:   db " + ", ".join(str(t * c) for _, t, c in DIVS) + "  ; ticks per page")
print("DivCells:  db " + ", ".join(str(TICKS_PER_PATTERN // t) for _, t, _ in DIVS) + "  ; cells in the whole pattern")
print("DivLabels:  ; 6 bytes each: 5 characters + terminator")
for label, _, _ in DIVS:
    print(f'    db "{label:<5}", 0')
print("PlayXPtrs: dw " + ", ".join(f"PlayX{i}" for i in range(len(DIVS))))
for i, (label, t, c) in enumerate(DIVS):
    xs = [dt * 8 // t for dt in range(c * t)]
    print(f"PlayX{i}:  ; {label}: {len(xs)} entries")
    for j in range(0, len(xs), 16):
        print("    db " + ",".join(str(x) for x in xs[j:j + 16]))
