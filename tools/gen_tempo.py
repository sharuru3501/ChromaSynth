#!/usr/bin/env python3
"""Generate src/tempo.inc: frames-per-16th-note for BPM 60..240 as 8.8 fixed point.

GB frame rate = 4194304 / 70224 = 59.7275 Hz.
A 16th note lasts 15 / BPM seconds, so frames = 15 * 59.7275 / BPM.
"""
FPS = 4194304 / 70224

print("; GENERATED by tools/gen_tempo.py -- do not edit by hand")
print("; index = BPM - 60, value = frames per 16th note * 256")
print("TempoTable:")
for bpm in range(60, 241):
    print(f"    dw {round(15 * FPS * 256 / bpm)} ; {bpm}")
