#!/usr/bin/env python3
"""Generate src/tempo.inc: frames per tick for BPM 60..240 as 8.8 fixed point.

12 ticks per beat (quarter note). GB frame rate = 4194304 / 70224 = 59.7275 Hz.
A tick lasts 60 / (BPM * 12) = 5 / BPM seconds, so frames = 5 * 59.7275 / BPM.
At BPM 240 that is 1.244 frames: always more than one frame, which is what lets
the sequencer process at most one tick per frame (see docs/ROLL_DESIGN.md).
"""
FPS = 4194304 / 70224

print("; GENERATED by tools/gen_tempo.py -- do not edit by hand")
print("; index = BPM - 60, value = frames per tick * 256")
print("TempoTable:")
for bpm in range(60, 241):
    v = round(5 * FPS * 256 / bpm)
    assert v > 256, "a tick must last more than one frame"
    print(f"    dw {v} ; {bpm}")
