#!/usr/bin/env python3
"""Generate src/pattern.inc: the demo pattern in tick units (12 ticks per beat).

The demo is written in 16th-note steps (1 step = 3 ticks): an arpeggio, a bass
line and hi-hats over two bars. Every channel gets 256 bytes (192 are used).
"""
TICKS_PER_STEP = 3
CELL_OFF = 0xFF
CHANNEL_BYTES = 256

# (start step, MIDI note, length in steps)
CH1 = [(0, 60, 2), (4, 64, 2), (8, 67, 2), (12, 64, 2), (16, 57, 2), (20, 60, 2), (24, 64, 2), (28, 60, 2)]
CH2 = []
CH3 = [(0, 48, 8), (8, 43, 8), (16, 45, 8), (24, 40, 8)]
CH4 = [(s, 90 if (s // 4) % 2 == 0 else 100, 1) for s in range(0, 32, 4)]


def channel(notes):
    cells = [0] * CHANNEL_BYTES
    for start, note, length in notes:
        cells[start * TICKS_PER_STEP] = note
    for start, note, length in notes:
        end = (start + length) * TICKS_PER_STEP
        if end < CHANNEL_BYTES and cells[end] == 0:
            cells[end] = CELL_OFF
    return cells


print("; GENERATED by tools/gen_pattern.py -- do not edit by hand")
print("DefaultPattern:  ; 4 channels x 256 bytes")
for name, notes in (("CH1", CH1), ("CH2", CH2), ("CH3", CH3), ("CH4", CH4)):
    cells = channel(notes)
    print(f"    ; {name}")
    for i in range(0, CHANNEL_BYTES, 16):
        print("    db " + ",".join(f"${c:02X}" for c in cells[i:i + 16]))
