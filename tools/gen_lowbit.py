#!/usr/bin/env python3
"""Generate src/lowbit.inc: for every byte value, the index of its lowest set bit (0 for 0).
Used by TakeRow (src/roll.asm) to find the next ring row that waits to be copied."""
print("; GENERATED by tools/gen_lowbit.py -- do not edit by hand")
for row in range(16):
    vals = []
    for i in range(row * 16, row * 16 + 16):
        vals.append(0 if i == 0 else (i & -i).bit_length() - 1)
    print("    db " + ",".join(str(v) for v in vals))
