#!/usr/bin/env python3
"""Generate the pulse-channel period table (MIDI note -> 11-bit GB period).

GB pulse frequency = 131072 / (2048 - x)  =>  x = 2048 - 131072 / f
The note range comes from inc/synth.inc (single source of truth).
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
text = (root / "inc" / "synth.inc").read_text()
LOW = int(re.search(r"DEF NOTE_MIN EQU (\d+)", text).group(1))
HIGH = int(re.search(r"DEF NOTE_MAX EQU (\d+)", text).group(1))

print("; GENERATED by tools/gen_notetable.py -- do not edit by hand")
print("NoteTable:")
for n in range(LOW, HIGH + 1):
    f = 440.0 * 2 ** ((n - 69) / 12)
    x = round(2048 - 131072 / f)
    x = max(0, min(2047, x))
    print(f"    dw ${x:04X} ; {n}")
